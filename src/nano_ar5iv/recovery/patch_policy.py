"""Apply ONLY M03 allowlisted operations inside a private disposable workspace."""
from __future__ import annotations
import difflib
import os
import stat
from dataclasses import asdict, dataclass
from pathlib import Path, PurePosixPath
from nano_ar5iv.domain.provenance import sha256_bytes, sha256_file
from nano_ar5iv.domain.source import SourceBundle
from nano_ar5iv.recovery.strategies import (APPEND_END, WRAPPER, RecoveryPlan,
                                            ALLOWED_STRATEGIES)


class RejectedPatch(ValueError):
    """Patch is untrusted, stale, or outside the bounded allowlist."""


@dataclass(frozen=True)
class PatchEvidence:
    strategy: str
    entry: str
    before_sha256: str | None
    after_sha256: str
    generated: bool
    diff: str

    def to_dict(self) -> dict:
        values = asdict(self)
        values.pop("diff")
        return values


def _safe_target(workspace: Path, value: str) -> Path:
    if not value or "\\" in value or "\x00" in value or value.startswith("/") or ":" in value:
        raise RejectedPatch("Unsafe target path")
    parts = PurePosixPath(value).parts
    if any(p in {".", "..", ""} for p in parts):
        raise RejectedPatch("Unsafe path traversal")
    target = workspace.joinpath(*parts)
    if not target.resolve(strict=False).is_relative_to(workspace.resolve()):
        raise RejectedPatch("Target leaves private workspace")
    return target


def apply_plan(workspace: Path, bundle: SourceBundle, plan: RecoveryPlan) -> PatchEvidence:
    if plan.source_bundle_id != bundle.bundle_id or plan.strategy not in ALLOWED_STRATEGIES:
        raise RejectedPatch("Unknown or stale repair plan")
    if len(plan.operations) != 1:
        raise RejectedPatch("Only one audited patch operation is permitted in M03")
    operation = plan.operations[0]
    target = _safe_target(workspace, operation.path)
    if plan.entry != operation.path or target.suffix.lower() not in {".tex", ".ltx"}:
        raise RejectedPatch("Patch must target the exact chosen TeX entry")
    if plan.strategy == WRAPPER and operation.action == "create_wrapper":
        if operation.path != "__nano_ar5iv_entry.tex" or target.exists() or target.is_symlink():
            raise RejectedPatch("Synthetic wrapper target must not exist")
        if len(operation.payload.encode("utf-8")) > 8192 or not operation.payload.startswith(r"\documentclass{"):
            raise RejectedPatch("Wrapper is invalid or too large")
        # The wrapper is generated by the trusted plan builder from explicit file list.
        # Repeat validation against the payload before writing to guard forged plans.
        from nano_ar5iv.recovery.wrapper import _CLASSES, _SAFE
        import re
        lines = operation.payload.splitlines()
        expected = re.fullmatch(r"\\documentclass\{([a-z]+)\}", lines[0])
        if not expected or expected.group(1) not in _CLASSES or lines[-1] != r"\end{document}":
            raise RejectedPatch("Wrapper document structure is invalid")
        contents = lines[1:-1]
        if contents.count(r"\begin{document}") != 1:
            raise RejectedPatch("Wrapper requires one document start")
        begin_idx = contents.index(r"\begin{document}")
        references = []
        for line in contents:
            match = re.fullmatch(r"\\input\{([^}]+)\}", line)
            if not match and line != r"\begin{document}":
                raise RejectedPatch("Non-allowlisted wrapper directive")
            if match:
                name = match.group(1)
                if not _SAFE.fullmatch(name) or ".." in name.split("/"):
                    raise RejectedPatch("Unsafe input reference")
                references.append(name)
        known = {f.path for f in bundle.files}
        if any(name not in known for name in references) or len(references) != len(set(references)):
            raise RejectedPatch("Unknown or duplicate wrapper fragment")
        target.write_bytes(operation.payload.encode("utf-8"))
        after = sha256_file(target)
        diff = f"--- /dev/null\n+++ b/{operation.path}\n" + "".join(
            "+" + line + "\n" for line in operation.payload.splitlines())
        return PatchEvidence(plan.strategy, plan.entry, None, after, True, diff)
    if plan.strategy == APPEND_END and operation.action == "append_end":
        known = {f.path: f.sha256 for f in bundle.files}
        if known.get(operation.path) != operation.expected_sha256:
            raise RejectedPatch("Source hash is not in immutable bundle")
        if operation.payload != "\n" + r"\end{document}" + "\n":
            raise RejectedPatch("Only exact end-document append is allowed")
        if not target.is_file() or target.is_symlink() or not stat.S_ISREG(target.stat().st_mode):
            raise RejectedPatch("Target is not a regular workspace file")
        before = sha256_file(target)
        if before != operation.expected_sha256:
            raise RejectedPatch("Workspace content changed since plan creation")
        with target.open("ab") as out:
            out.write(operation.payload.encode("utf-8"))
        after = sha256_file(target)
        diff = (f"--- a/{operation.path}\n+++ b/{operation.path}\n"
                "@@ appended-at-eof @@\n+" + r"\end{document}" + "\n")
        return PatchEvidence(plan.strategy, plan.entry, before, after, False, diff)
    raise RejectedPatch("Strategy/operation mismatch")
